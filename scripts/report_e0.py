"""Render docs/reproduction_report.md from the E0 result files (no hand-copied numbers)."""

from __future__ import annotations

import numpy as np
import pandas as pd

OUT = "docs/reproduction_report.md"


def md(df: pd.DataFrame, digits: int = 4) -> str:
    df = df.copy()
    if "eps" in df.columns:
        df["eps"] = df["eps"].map(lambda v: f"{v:g}")
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{digits}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def corrected_summary(path: str) -> pd.DataFrame:
    c = pd.read_parquet(path)
    c["err2"] = (c["point"] - c["truth"]) ** 2
    rows = []
    for key, g in c.groupby(["outcome", "eps", "design", "estimator"]):
        f = g[g["feasible"].astype(bool)]
        ok = np.isfinite(f["ci_low"])
        cov = ((f["ci_low"] <= f["truth"]) & (f["truth"] <= f["ci_high"]))[ok]
        rows.append(dict(zip(["outcome", "eps", "design", "estimator"], key, strict=True),
                         rmse=float(np.sqrt(f["err2"].mean())) if len(f) else np.nan,
                         feasible=float(g["feasible"].mean()),
                         coverage=float(cov.mean()) if ok.any() else np.nan))
    return pd.DataFrame(rows)


def main() -> None:
    t2 = pd.read_csv("results/E0_table2_comparison.csv")
    d2 = pd.read_csv("results/E0_tableD2_comparison.csv")
    pairs = [("naive", "naive"), ("deletion", "deletion"), ("flag_ppi", "ppi"),
             ("strat_rc_ppi", "rc_strat")]
    max_t2 = max(float((t2[f"paper_{a}"] - t2[f"l8_{b}"]).abs().max()) for a, b in pairs)
    max_d2 = max(float((d2[f"paper_{a}"] - d2[f"l8_{b}"]).abs().max()) for a, b in pairs)

    rep = t2[["outcome", "eps", "paper_flag_ppi", "l8_ppi", "paper_strat_rc_ppi",
              "l8_rc_strat", "l8_fallback_share", "lm_ppi", "lm_rc_strat", "lm_rc_strat_raw",
              "lm_fallback_share"]].rename(columns={
        "paper_flag_ppi": "flag-PPI paper", "l8_ppi": "flag-PPI v1 (8)",
        "paper_strat_rc_ppi": "strat paper", "l8_rc_strat": "strat v1 (8)",
        "l8_fallback_share": "fallback (8)", "lm_ppi": "flag-PPI v1 (200)",
        "lm_rc_strat": "strat v1 (200)", "lm_rc_strat_raw": "strat no fallback (200)",
        "lm_fallback_share": "fallback (200)"})

    s = corrected_summary("results/raw/E0_corrected.parquet")
    keep = ["naive", "deletion", "hajek", "flag_ppi", "rc_ppi", "rc_ppi_pp"]
    rmse = s[s.estimator.isin(keep)].pivot_table(index=["outcome", "eps", "design"],
                                                 columns="estimator", values="rmse")[keep]
    feas = s[s.estimator == "rc_ppi_pp"].pivot_table(index=["outcome", "eps"],
                                                     columns="design", values="feasible")
    cov = s[s.estimator.isin(["hajek", "flag_ppi", "rc_ppi_pp"])].pivot_table(
        index=["outcome", "eps", "design"], columns="estimator", values="coverage")
    raw = pd.read_parquet("results/raw/E0_corrected.parquet")
    n_rep = int(raw["rep"].max() + 1)
    m_ai = (raw.drop_duplicates(["domain", "generator", "eps", "design", "rep"])
            .groupby(["design", "eps"])["m_machine"].mean().unstack())

    text = f"""# Reproduction report (stage S3, experiment E0)

Generated by `scripts/report_e0.py` from `results/`. Data: Ghostbuster feature table
`data/features/ghostbuster_tfidf.parquet` (TF-IDF detector trained cross-domain on human
vs GPT; Claude documents form the generator-shift condition). Grid as in the first
submission: 3 domains x 2 generators x contamination 0.05-0.30, N = 900, audit 5%.

## 1. The first submission is reproduced exactly

Running the v1 code path (`d2vi.estimators.legacy`) with the paper's 8 seeds reproduces
every cell of Table 2 (32 numbers) and Table D.2 (96 numbers): the largest absolute
difference is {max_t2:.1e} for Table 2 and {max_d2:.1e} for Table D.2, i.e. rounding
in the fourth decimal. The detector operating points also match Table 1 exactly.

This required one correction to the paper's description of the detector: the v1 code
used `min_df = 1` (scikit-learn's default), not `min_df = 2` as written in Section 4.4.
With `min_df = 2` one more essay is flagged and the deletion column no longer matches.

## 2. What the v1 numbers contained

The "stratified RC-PPI" column silently reported flag-PPI whenever stratified RC-PPI
abstained (finding F2). The share of such replications, and the effect of using more
replications, are:

{md(rep)}

`fallback` is the share of replications in which the reported "stratified RC-PPI" value
was actually flag-PPI. `strat no fallback` is the RMSE of stratified RC-PPI over its
feasible replications only (a selected subset; see Section 3 for the intention-to-treat
view through the policy). Columns marked (200) use 200 seeds of the same v1 code: with
8 seeds several cells move by 20-30% (for example flag-PPI on sentiment at 5%
contamination), so the original Monte Carlo error was large (finding F10).

## 3. Corrected pipeline on the same cells (preview, development data only)

{n_rep} replications per cell; every estimator in a replication uses the same audit of
exactly 45 records; RMSE over feasible replications; RC-PPI never falls back.

RMSE pooled over domains and generators:

{md(rmse.reset_index())}

Feasibility of RC-PPI++ (share of replications with at least 6 audited machine and 6
audited human records, and 3 of each per training fold):

{md(feas.reset_index(), 3)}

Mean number of audited machine records:

{md(m_ai.reset_index(), 2)}

Coverage of 95% design-based intervals:

{md(cov.reset_index(), 3)}

## 4. Reading

* Where it is feasible, RC-PPI(++) has lower RMSE than flag-PPI in every cell, often by
  a factor of 2-5 (for example sentiment at 5% contamination with the top-decile audit).
* A random 45-record audit makes RC-PPI feasible in only a few percent of replications at
  5% contamination (Proposition 3); the top-decile design raises the audited machine
  count about threefold and feasibility to about two thirds. At 20-30% contamination the
  top-decile design is worse than simple random sampling, because the inverse-probability
  weights add variance once machine records are no longer rare.
* The naive mean is the most accurate estimator for sentiment in this shift regime, as in
  the first submission; this is the case the selection policy must handle.
* Coverage of the linearised interval is close to nominal for the Hajek estimator and
  for RC-PPI under simple random audits, but drops to about 0.89-0.93 for RC-PPI under the
  top-decile design. Stage S4 must address this before the protocol is frozen (candidates:
  Rao-Wu bootstrap, a small-sample degrees-of-freedom rule, or a variance floor).

These are development results. Defaults are chosen on them in stage S4; held-out corpora
are not touched until the protocol is frozen.
"""
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(OUT)


if __name__ == "__main__":
    main()
