def numbers(e: dict, b: dict, ph: dict, cells: pd.DataFrame) -> str:
    p1, p2, p3 = e["PE1"], e["PE2"], e["PE3"]
    p4 = e["PE4"]["pooled"]["rules"]
    ex, best = ph["excess_srmse"]["overall"], ph["best_single"]["overall"]
    ch = ph["deletion_channels"]
    sec = pd.read_csv(RES / "S5_final_secondary.csv")
    small = sec[sec.grid == "small_budget"].iloc[0]
    est = pd.read_csv(RES / "S5_all_estimators.csv")
    est = est[est.corpus == "all five"].set_index("estimator")
    anes = json.loads((RES / "S5_anes_descriptives.json").read_text())
    rob = anes["detectors"]["roberta"]
    m = {
        "nCorpora": str(cells.corpus.nunique()),
        "nPools": str(cells.pool.nunique()),
        "nCells": num(len(cells)),
        "nReps": num(int(cells.n_rep.iloc[0])),
        "PEoneITT": f(p1["itt"]["pooled_ratio"], 2),
        "PEoneITTlo": f(p1["itt"]["pooled_ratio_bca90"][0], 2),
        "PEoneITThi": f(p1["itt"]["pooled_ratio_bca90"][1], 2),
        "PEonePP": f(p1["per_protocol"]["pooled_ratio"], 2),
        "PEonePPlo": f(p1["per_protocol"]["pooled_ratio_bca90"][0], 2),
        "PEonePPhi": f(p1["per_protocol"]["pooled_ratio_bca90"][1], 2),
        "PEoneP": f(p1["itt"]["wilcoxon_p_one_sided"]),
        "PEoneGain": pct(1 - p1["itt"]["pooled_ratio"], 0),
        "PEonePoolsAbove": str(b["pe1_pools_above_one"]["n"]),
        "PEonePoolsAboveBig": str(b["pe1_pools_above_one"]["n_above_1.3"]),
        "PEoneMaxPool": f(b["pe1_pools_above_one"]["max"], 2),
        "FeasibleShare": pct(p1["feasible_share_of_replications"], 0),
        "NeverFeasible": pct(p1["cells_never_feasible"]),
        "PEtwoMean": f(p2["mean_coverage"]),
        "PEtwoShare": pct(p2["share_cells_ge_090"]),
        "PEtwoMin": f(p2["min_coverage"]),
        "PEtwoLowCells": str(b["low_coverage_cells"]["n"]),
        "PEtwoLowCellsRAID": str(b["low_coverage_cells"]["by_corpus"]["raid"]),
        "PEtwoWidth": f(p2["median_width_ratio"], 2),
        "PEtwoWidthTwo": f(p2["by_budget"]["0.02"]["median_width_ratio"], 2),
        "PEtwoWidthFive": f(p2["by_budget"]["0.05"]["median_width_ratio"], 2),
        "PEtwoWidthTen": f(p2["by_budget"]["0.1"]["median_width_ratio"], 2),
        "PEthreeRate": pct(p3["bad"]["rate"], 2),
        "PEthreeUpper": pct(p3["bad"]["upper95_cluster_bootstrap"], 2),
        "PEthreeNear": pct(p3["near"]["rate"], 2),
        "PEthreeNearUpper": pct(p3["near"]["upper95_cluster_bootstrap"], 2),
        "PEthreeReps": num(p3["bad"]["replications"]),
        "PEthreePower": pct(p3["power_small_bias"], 0),
        "PEthreeWorst": pct(p3["worst_cell_rate"]),
        "PEthreeCells": num(b["pe3_cells"]["cells_with_30_bad"]),
        "PEthreeCellsAbove": str(b["pe3_cells"]["above_0.075"]),
        **{
            f"Regret{k}": f(p4[r]["max_excess_srmse"])
            for k, r in [
                ("Policy", "policy_debiased"),
                ("RC", "rc_ppi_pp"),
                ("Hajek", "hajek"),
                ("Flag", "flag_ppi"),
                ("Deletion", "deletion"),
                ("Naive", "naive"),
            ]
        },
        **{
            f"Pooled{k}": f(p4[r]["pooled_srmse"])
            for k, r in [
                ("Policy", "policy_debiased"),
                ("RC", "rc_ppi_pp"),
                ("Hajek", "hajek"),
                ("Flag", "flag_ppi"),
                ("Deletion", "deletion"),
                ("Naive", "naive"),
            ]
        },
        "MeanExcessPolicy": f(p4["policy_debiased"]["mean_excess_srmse"]),
        "MeanExcessDeletion": f(p4["deletion"]["mean_excess_srmse"]),
        "BestDeletion": pct(best["deletion"], 0),
        "BestNaive": pct(best["naive"], 0),
        "BestRC": pct(best["rc_ppi_pp"], 0),
        "BestFlag": pct(best["flag_ppi"], 0),
        "DeletionAboveTwoTenths": pct(ex["deletion"]["share_above"]["0.2"]),
        "NaiveAboveTwoTenths": pct(ex["naive"]["share_above"]["0.2"]),
        "PolicyAboveOneTenth": pct(ex["policy_debiased"]["share_above"]["0.1"]),
        "ChannelPairs": str(ch["by_eps"]["0.2"]["pool_outcomes"]),
        "ChannelMaterial": str(ch["by_eps"]["0.2"]["material"]),
        "ChannelResidual": str(ch["by_eps"]["0.2"]["dominant"].get("residual", 0)),
        "ChannelSelection": str(ch["by_eps"]["0.2"]["dominant"].get("selection", 0)),
        "ChannelMaxSelection": f(ch["selection_term"]["max_abs"], 2),
        "ChannelCheckCorr": f(ch["check_against_simulation"]["correlation"], 4),
        "SmallBudgetITT": f(small.srmse_itt),
        "SmallBudgetPolicy": f(small.srmse_policy_debiased),
        "SmallBudgetDeletion": f(small.srmse_deletion),
        "SmallBudgetNaive": f(small.srmse_naive),
        "MomentSRMSE": f(est.loc["moment", "srmse"], 2),
        "MomentCoverage": f(est.loc["moment", "coverage"], 2),
        "MomentFeasible": pct(est.loc["moment", "feasible"], 0),
        "AnesHumans": num(anes["human_records"]),
        "AnesRobertaFPR": pct(rob["false_positive_rate"]),
        "AnesRobertaFPRWeb": pct(rob["fpr_by_mode"]["web"]),
        "AnesRobertaFPRFace": pct(rob["fpr_by_mode"]["face-to-face"]),
        "AnesMaxSelection": f(
            max(
                abs(x) for d in anes["detectors"].values() for x in d["selection_term_sd"].values()
            ),
            3,
        ),
    }
    lines = ["% generated by scripts/make_tables.py; do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "paper" / "generated"))
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    e = json.loads((RES / "S5_endpoints.json").read_text())
    b = json.loads((RES / "S5_breakdowns.json").read_text())
    ph = json.loads((RES / "S5_posthoc_descriptives.json").read_text())
    cells = load_cells()
    tables = {
        "tab_corpora": tab_corpora(cells),
        "tab_operating_points": tab_operating_points(),
        "tab_endpoints": tab_endpoints(e, b),
        "tab_pe1_corpus": tab_pe1_corpus(e, cells),
        "tab_pe4": tab_pe4(e),
        "tab_rules": tab_rules(cells, ph),
        "tab_estimators9": tab_estimators9(),
        "tab_designs": tab_designs(b),
        "tab_coverage": tab_coverage(e, b),
        "tab_feasibility": tab_feasibility(b),
        "tab_robustness": tab_robustness(),
        "tab_verification": tab_verification(),
        "tab_channels": tab_channels(ph),
        "tab_raid": tab_raid(b),
        "tab_languages": tab_languages(b),
    }
    for name, tex in tables.items():
        (out / f"{name}.tex").write_text(tex)
    (out / "numbers.tex").write_text(numbers(e, b, ph, cells))
    print(f"written {len(tables)} tables and numbers.tex to {out}")


if __name__ == "__main__":
    main()
