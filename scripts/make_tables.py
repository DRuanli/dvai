def f(x: float, nd: int = 3) -> str:
    return f"{x:.{nd}f}"


def pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}\\%"


def num(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def tabular(spec: str, header: list[str], rows: list[list[str]], note: str = "") -> str:
    out = [
        f"% generated by scripts/make_tables.py; do not edit{note}",
        f"\\begin{{tabular}}{{{spec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
    ]
    for r in rows:
        out.append(r[0] if len(r) == 1 else " & ".join(r) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(out)


def bold_min(values: list[float], nd: int = 3) -> list[str]:
    lo = min(values)
    return [f"\\textbf{{{f(v, nd)}}}" if v == lo else f(v, nd) for v in values]


def load_cells() -> pd.DataFrame:
    return pd.concat(
        [pd.read_parquet(p) for p in sorted((COMPACT / "primary").glob("*.cells.parquet"))],
        ignore_index=True,
    )


def manifests(grid: str = "primary") -> dict:
    return {
        p.name.split(".")[0]: json.loads(p.read_text())
        for p in sorted((COMPACT / grid).glob("*.manifest.json"))
    }


