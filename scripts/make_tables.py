def tab_corpora(cells: pd.DataFrame) -> str:
    man = manifests()
    rows = []
    for c in ORDER:
        pools = {k: v for k, v in man[c]["pools"].items() if v.get("cells_run")}
        hum = [v["human"] for v in pools.values()]
        mac = [v["machine"] for v in pools.values()]
        sub = cells[cells.corpus == c]
        dets = sorted({p.split("__")[-1] for p in pools}, key=list(DETECTOR).index)

        def rng(v):
            return num(min(v)) if min(v) == max(v) else f"{num(min(v))}--{num(max(v))}"

        rows.append(
            [
                CORPUS[c],
                str(len(pools)),
                rng(hum),
                rng(mac),
                ", ".join(DETECTOR[d] for d in dets),
                str(sub.outcome.nunique()),
                num(len(sub)),
            ]
        )
    rows.append(["\\midrule"])
    rows.append(
        [
            "All",
            str(cells.pool.nunique()),
            "",
            "",
            "",
            str(cells.outcome.nunique()),
            num(len(cells)),
        ]
    )
    return tabular(
        "lrrrp{5.2cm}rr",
        ["Corpus", "Pools", "Human records", "Machine records", "Detectors", "Outcomes", "Cells"],
        rows,
    )


def tab_operating_points() -> str:
    ops = pd.read_csv(RES / "S5_heldout_operating_points.csv")
    evaluated = {
        p.name[: -len(".cells.parquet")] for p in (COMPACT / "primary").glob("*.cells.parquet")
    }
    rows = []
    for c in ORDER:
        for det in [d for d in DETECTOR if d in set(ops[ops.corpus == c].detector)]:
            g = ops[(ops.corpus == c) & (ops.detector == det)]
            h, m = g[g.group == "human"], g[g.group != "human"]
            names = [
                f"{c}__{r.group if r.domain == 'all' else r.domain + '-' + r.group}__{det}"
                for r in m.itertuples()
            ]
            m = m[[n in evaluated for n in names]]
            h = h[h.domain.isin(set(m.domain))]
            fpr = (
                f(h.flagged.min()) if len(h) == 1 else f"{f(h.flagged.min())}--{f(h.flagged.max())}"
            )
            rows.append(
                [
                    CORPUS[c],
                    DETECTOR[det],
                    str(len(h)),
                    fpr,
                    str(len(m)),
                    f(m.flagged.min()),
                    f(m.flagged.median()),
                    f(m.flagged.max()),
                ]
            )
        rows.append(["\\addlinespace"])
    rows.pop()
    return tabular(
        "llrlrrrr",
        [
            "Corpus",
            "Detector",
            "Human pools",
            "False-positive rate",
            "Machine groups",
            "Sens.\\ min",
            "median",
            "max",
        ],
        rows,
    )


def tab_endpoints(e: dict, b: dict) -> str:
    p1, p2, p3 = e["PE1"], e["PE2"], e["PE3"]
    itt, pp = p1["itt"], p1["per_protocol"]
    bad, near = p3["bad"], p3["near"]
    worst = {r: f(v["max_excess_srmse"]) for r, v in e["PE4"]["pooled"]["rules"].items()}

    def ratio(v: dict) -> str:
        lo, hi = v["pooled_ratio_bca90"]
        return f"{f(v['pooled_ratio'], 2)} [{f(lo, 2)}, {f(hi, 2)}]"

    def holds(flag: bool) -> str:
        return "yes" if flag else "no"

    rows = [
        [
            "PE1",
            "RC-PPI++ is non-inferior to flag-PPI on the same audit (MSE ratio, margin 1.10)",
            f"ITT {ratio(itt)}; per protocol {ratio(pp)}; "
            f"$p = {f(itt['wilcoxon_p_one_sided'])}$ for both",
            holds(p1["passes"]),
        ],
        [
            "PE2",
            "95\\% intervals are valid: mean coverage $\\ge 0.93$ and "
            "$\\ge 90\\%$ of cells $\\ge 0.90$",
            f"mean {f(p2['mean_coverage'])}; {pct(p2['share_cells_ge_090'])} of cells "
            f"$\\ge 0.90$; lowest cell {f(p2['min_coverage'])}; median width "
            f"{f(p2['median_width_ratio'], 2)} $\\times$ oracle",
            holds(p2["passes"]),
        ],
        [
            "PE3",
            "TOST ($\\tau = 0.2$ SD) controls false certification: upper 95\\% bound $\\le 0.075$",
            f"{pct(bad['rate'], 2)} (upper {pct(bad['upper95_cluster_bootstrap'], 2)}); "
            f"near the boundary {pct(near['rate'], 2)} "
            f"(upper {pct(near['upper95_cluster_bootstrap'], 2)}); "
            f"worst cell {pct(p3['worst_cell_rate'])}; "
            f"certifies {pct(p3['power_small_bias'], 0)} at small bias",
            holds(p3["passes"]),
        ],
        [
            "PE4",
            "The policy has the lowest worst-case excess sRMSE (descriptive)",
            f"policy {worst['policy_debiased']}; RC-PPI++ {worst['rc_ppi_pp']}; "
            f"H\\'ajek {worst['hajek']}; flag-PPI {worst['flag_ppi']}; "
            f"deletion {worst['deletion']}; naive {worst['naive']}",
            holds(e["PE4"]["pooled"]["policy_is_lowest"]),
        ],
    ]
    return tabular(
        "lp{5.0cm}p{7.6cm}l", ["", "Claim and decision rule", "Held-out result", "Holds"], rows
    )


def tab_pe1_corpus(e: dict, cells: pd.DataFrame) -> str:
    per = cells.groupby(["corpus", "pool"]).agg(
        a=("mse_rc_ppi_pp", "sum"), b=("mse_flag_ppi", "sum")
    )
    per["r"] = per.a / per.b
    rows = []
    for c in ORDER:
        r = per.loc[c].r
        rows.append(
            [
                CORPUS[c],
                str(len(r)),
                f(e["PE1"]["itt"]["per_unit_ratio"][c], 2),
                f(e["PE1"]["per_protocol"]["per_unit_ratio"][c], 2),
                str(int((r > 1).sum())),
                f(r.max(), 2),
            ]
        )
    rows.append(["\\midrule"])
    rows.append(
        [
            "Pooled",
            str(len(per)),
            f(e["PE1"]["itt"]["pooled_ratio"], 2),
            f(e["PE1"]["per_protocol"]["pooled_ratio"], 2),
            str(int((per.r > 1).sum())),
            f(per.r.max(), 2),
        ]
    )
    return tabular(
        "lrrrrr",
        [
            "Corpus",
            "Pools",
            "ITT ratio",
            "Per-protocol ratio",
            "Pools with ratio $> 1$",
            "Largest pool ratio",
        ],
        rows,
    )


def tab_pe4(e: dict) -> str:
    rows = []
    for label, block in [
        ("All budgets", e["PE4"]["pooled"]),
        *[(f"Budget {pct(float(b), 0)}", v) for b, v in e["PE4"]["by_budget"].items()],
    ]:
        vals = [block["rules"][r]["max_excess_srmse"] for r in ["policy_debiased", *SINGLES]]
        rows.append([label, *bold_min(vals)])
    rows.append(["\\midrule"])
    pooled = e["PE4"]["pooled"]["rules"]
    rows.append(
        [
            "Mean excess",
            *bold_min([pooled[r]["mean_excess_srmse"] for r in ["policy_debiased", *SINGLES]]),
        ]
    )
    rows.append(
        [
            "Pooled sRMSE",
            *bold_min([pooled[r]["pooled_srmse"] for r in ["policy_debiased", *SINGLES]]),
        ]
    )
    return tabular(
        "l" + "r" * 6,
        ["Worst-case excess sRMSE", *[RULE[r] for r in ["policy_debiased", *SINGLES]]],
        rows,
    )


def tab_rules(cells: pd.DataFrame, ph: dict) -> str:
    rows = []
    for c in [*ORDER, None]:
        g = cells if c is None else cells[cells.corpus == c]
        if c is None:
            rows.append(["\\midrule"])
        vals = [float(np.sqrt(g[f"mse_{r}"].mean())) for r in SIX]
        best = ph["best_single"]["overall" if c is None else "by_corpus"]
        best = best if c is None else best[c]
        rows.append(
            [
                "All" if c is None else CORPUS[c],
                *bold_min(vals),
                f(g.cover_itt.mean()),
                pct(best.get("deletion", 0), 0),
                pct(best.get("naive", 0), 0),
                pct(best.get("rc_ppi_pp", 0), 0),
            ]
        )
    return tabular(
        "l" + "r" * 10,
        [
            "Corpus",
            *[RULE[r] for r in SIX],
            "Coverage",
            "Del.\\ best",
            "Naive best",
            "RC best",
        ],
        rows,
    )


